Sie sollen eine Datenbank für einen Fußballverein entwickeln. Im Verein gibt es mehrere Mann-
schaften (mit ID und Bezeichnung), denen jeweils mehrere Spieler (mit ID, Name, Geburtsdatum

und Spielerpass-Nr.) eindeutig zugeordnet sind. Darüber hinaus wird jede Mannschaft von einem

Trainer (mit ID, Name, Geburtsdatum und Trainerlizenz) und einem Co-Trainer trainiert (der Co-
Trainer ist auch ein Trainer!). Jeder Spieler wird in verschiedenen Spielen (mit ID, Spieltag und 
Name des Gegners) eingesetzt. In einem Spiel können die Spieler unterschiedliche Positionen und

Einsatzzeiten haben.
a) Erstellen Sie ein ER-Modell für die Datenbank mit Entitätstypen, Beziehungen,
Kardinalitäten und Attributen.
b) Wandeln Sie das ER-Modell in ein relationales Tabellenmodell um. Konkretisieren Sie die
Beziehungen zwischen den Tabellen, indem Sie zusätzlich zu den bereits bekannten
Attributen auch Primär- und Fremdschlüssel bestimmen.